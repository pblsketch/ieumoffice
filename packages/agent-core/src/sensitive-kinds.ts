/** A kind's name in the screen language (English for a language the table does not know). */
export function sensitiveKindName(kind: SensitiveKind, lang: string): string {
  return SENSITIVE_KIND_NAMES[hidingLangOf(lang)][kind]
}

/** Kinds whose values are numbers or codes, compared with spaces and dashes removed. */
const NUMBER_LIKE: ReadonlySet<SensitiveKind> = new Set([
  'resident-number',
  'passport',
  'driver-license',
  'account',
  'card',
  'phone',
  'birth-date',
  'id-number',
  'vehicle',
])

/**
 * The form two values of a kind are compared in: the same person written
 * twice with different spacing is one value.
 */
export function normalizeSensitiveValue(kind: SensitiveKind, value: string): string {
  const v = value.normalize('NFC')
  if (NUMBER_LIKE.has(kind)) return v.replace(/[\s\-‐-―−]/g, '').toUpperCase()
  if (kind === 'email') return v.trim().toLowerCase()
  return v.replace(/\s+/g, ' ').trim()
}
